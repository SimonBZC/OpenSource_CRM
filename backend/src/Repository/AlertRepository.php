<?php

declare(strict_types=1);

namespace App\Repository;

use App\Entity\Alert;
use App\Entity\Opportunity;
use App\Enum\AlertStatus;
use Doctrine\Bundle\DoctrineBundle\Repository\ServiceEntityRepository;
use Doctrine\Persistence\ManagerRegistry;

/**
 * @extends ServiceEntityRepository<Alert>
 */
class AlertRepository extends ServiceEntityRepository
{
    public function __construct(ManagerRegistry $registry)
    {
        parent::__construct($registry, Alert::class);
    }

    /**
     * Détection d'idempotence pour
     * App\Automation\Rule\CreateAlertForHighScoreOpportunityRule : indique
     * s'il existe déjà, pour cette opportunité, une alerte auto-générée
     * (identifiée par son titre exact — voir le PHPDoc de la règle pour les
     * limites de cette approche) qui n'est ni DONE ni CANCELLED, c'est-à-dire
     * encore "active".
     */
    public function hasActiveAutoGeneratedAlertForOpportunity(Opportunity $opportunity, string $autoGeneratedTitle): bool
    {
        $count = $this->createQueryBuilder('t')
            ->select('COUNT(t.id)')
            ->andWhere('t.opportunity = :opportunity')
            ->andWhere('t.title = :title')
            ->andWhere('t.status NOT IN (:terminalStatuses)')
            ->setParameter('opportunity', $opportunity)
            ->setParameter('title', $autoGeneratedTitle)
            ->setParameter('terminalStatuses', [AlertStatus::DONE, AlertStatus::CANCELLED])
            ->getQuery()
            ->getSingleScalarResult();

        return $count > 0;
    }
}
