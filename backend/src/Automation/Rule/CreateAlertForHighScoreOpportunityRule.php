<?php

declare(strict_types=1);

namespace App\Automation\Rule;

use App\Automation\AutomationRuleInterface;
use App\Automation\Event\OpportunityAnalyzed;
use App\Entity\Alert;
use App\Enum\AlertPriority;
use App\Enum\AlertStatus;
use App\Repository\AlertRepository;
use Doctrine\ORM\EntityManagerInterface;

/**
 * Sur OpportunityAnalyzed : si le score de l'opportunité est >= au seuil
 * configuré, crée automatiquement une Alerte de relance.
 *
 * Seuil : le dashboard (Phase 5) affiche "fort potentiel" dès score >= 70.
 * Cette automatisation utilise volontairement un seuil PLUS SÉLECTIF (80
 * par défaut, voir %app.automation.high_score_threshold% dans
 * config/services.yaml) pour éviter de spammer l'utilisateur d'alertes dès
 * qu'une opportunité franchit le seuil d'affichage du dashboard. Décision
 * d'orchestration assumée, pas une invention de cet agent.
 *
 * Idempotence : POST /api/opportunities/{id}/analyze peut être rappelé
 * plusieurs fois sur la même opportunité. Pour éviter de créer une alerte en
 * double, cette règle ne s'appuie PAS sur un nouveau champ en base (donc
 * aucune migration de schéma) mais sur le TITRE EXACT de l'alerte
 * auto-générée (voir AUTO_ALERT_TITLE), combiné à l'opportunité liée et à un
 * statut différent de DONE et de CANCELLED (voir
 * AlertRepository::hasActiveAutoGeneratedAlertForOpportunity()).
 * C'est un mécanisme FRAGILE et documenté comme tel : si ce titre exact est
 * modifié manuellement par un utilisateur sur une alerte existante, ou si
 * une alerte portant fortuitement le même titre est créée manuellement, la
 * détection peut se tromper (fausse détection de doublon, ou au contraire
 * doublon non détecté). Aucun marqueur persistant dédié n'a été ajouté en
 * base sans validation préalable, conformément à la consigne.
 *
 * Une opportunité dont le contact est inactif ne donne pas d'alerte ; sans
 * contact, elle reste traitée.
 */
final class CreateAlertForHighScoreOpportunityRule implements AutomationRuleInterface
{
    public const AUTO_ALERT_TITLE = 'Relancer rapidement — fort potentiel';

    public function __construct(
        private readonly AlertRepository $alertRepository,
        private readonly EntityManagerInterface $entityManager,
        private readonly int $highScoreThreshold = 80,
    ) {
    }

    public function getName(): string
    {
        return 'create_alert_for_high_score_opportunity';
    }

    public function supports(object $event): bool
    {
        return $event instanceof OpportunityAnalyzed;
    }

    public function execute(object $event): void
    {
        if (!$event instanceof OpportunityAnalyzed) {
            return;
        }

        $opportunity = $event->opportunity;

        // Contact inactif : pas d'alerte. Une opportunité sans contact reste traitée.
        if (false === $opportunity->getContact()?->isActive()) {
            return;
        }

        $score = $opportunity->getScore();

        if (null === $score || $score < $this->highScoreThreshold) {
            return;
        }

        if ($this->alertRepository->hasActiveAutoGeneratedAlertForOpportunity($opportunity, self::AUTO_ALERT_TITLE)) {
            return;
        }

        $descriptionLines = [
            sprintf(
                "Alerte créée automatiquement par l'analyse IA de l'opportunité « %s » (score : %d/100).",
                $opportunity->getTitle(),
                $score,
            ),
        ];

        if (null !== $opportunity->getScoreReason() && '' !== $opportunity->getScoreReason()) {
            $descriptionLines[] = 'Raison du score : '.$opportunity->getScoreReason();
        }

        $alert = new Alert();
        $alert->setTitle(self::AUTO_ALERT_TITLE);
        $alert->setDescription(implode("\n\n", $descriptionLines));
        $alert->setPriority(AlertPriority::HIGH);
        $alert->setStatus(AlertStatus::TODO);
        // Échéance à J+2 : simple et justifiable pour une relance "rapide"
        // sans être irréaliste dans un usage quotidien du CRM.
        $alert->setDueDate((new \DateTimeImmutable())->modify('+2 days'));
        $alert->setOpportunity($opportunity);

        $this->entityManager->persist($alert);
        $this->entityManager->flush();
    }
}
