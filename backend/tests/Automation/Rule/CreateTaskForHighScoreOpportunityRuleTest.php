<?php

declare(strict_types=1);

namespace App\Tests\Automation\Rule;

use App\Automation\Event\FollowUpDue;
use App\Automation\Event\OpportunityAnalyzed;
use App\Automation\Event\OpportunityCreated;
use App\Automation\Rule\CreateTaskForHighScoreOpportunityRule;
use App\Ai\Dto\OpportunityAnalysisResult;
use App\Entity\Opportunity;
use App\Entity\Task;
use App\Enum\TaskPriority;
use App\Enum\TaskStatus;
use App\Repository\TaskRepository;
use Doctrine\ORM\EntityManagerInterface;
use PHPUnit\Framework\TestCase;

/**
 * Tests unitaires de App\Automation\Rule\CreateTaskForHighScoreOpportunityRule.
 *
 * L'événement `dueDate` de la Task créée est calculé via
 * `(new \DateTimeImmutable())->modify('+2 days')`. L'extension ClockMock de
 * symfony/phpunit-bridge (voir clock-mock-namespaces=App dans
 * phpunit.dist.xml) ne mocke que les fonctions PHP userland time(),
 * microtime(), date(), sleep()/usleep() appelées dans le namespace ciblé :
 * elle n'intercepte PAS la construction d'un \DateTimeImmutable (classe
 * native, pas une fonction). Le test de dueDate ci-dessous vérifie donc une
 * fenêtre de tolérance autour de "maintenant + 2 jours" plutôt que de
 * dépendre d'une horloge figée.
 */
final class CreateTaskForHighScoreOpportunityRuleTest extends TestCase
{
    private function makeOpportunity(?int $score, ?string $scoreReason = null): Opportunity
    {
        return (new Opportunity())
            ->setTitle('Développeur Symfony senior')
            ->setScore($score)
            ->setScoreReason($scoreReason);
    }

    private function makeAnalysisResult(): OpportunityAnalysisResult
    {
        return new OpportunityAnalysisResult(
            score: 80,
            relevant: true,
            technologies: [],
            tjmMin: null,
            tjmMax: null,
            remote: null,
            location: null,
            duration: null,
            startDate: null,
            reason: 'Bonne correspondance.',
            missingInformation: [],
        );
    }

    // --- supports() ----------------------------------------------------------

    public function testSupportsReturnsTrueOnlyForOpportunityAnalyzed(): void
    {
        $rule = new CreateTaskForHighScoreOpportunityRule(
            $this->createMock(TaskRepository::class),
            $this->createMock(EntityManagerInterface::class),
        );

        $opportunity = $this->makeOpportunity(80);

        self::assertTrue($rule->supports(new OpportunityAnalyzed($opportunity, $this->makeAnalysisResult(), ['score', 'scoreReason'])));
        self::assertFalse($rule->supports(new OpportunityCreated($opportunity)));
        self::assertFalse($rule->supports(new FollowUpDue(new \App\Entity\FollowUp())));
        self::assertFalse($rule->supports(new \stdClass()));
    }

    // --- Seuil -----------------------------------------------------------------

    public function testExecuteCreatesTaskWhenScoreIsAtOrAboveThreshold(): void
    {
        $opportunity = $this->makeOpportunity(80);

        $taskRepository = $this->createMock(TaskRepository::class);
        $taskRepository->method('hasActiveAutoGeneratedTaskForOpportunity')->willReturn(false);

        $entityManager = $this->createMock(EntityManagerInterface::class);
        $entityManager->expects(self::once())->method('persist')->with(self::isInstanceOf(Task::class));
        $entityManager->expects(self::once())->method('flush');

        $rule = new CreateTaskForHighScoreOpportunityRule($taskRepository, $entityManager, 80);

        $rule->execute(new OpportunityAnalyzed($opportunity, $this->makeAnalysisResult(), ['score', 'scoreReason']));
    }

    public function testExecuteDoesNothingWhenScoreIsJustBelowThreshold(): void
    {
        $opportunity = $this->makeOpportunity(79);

        $taskRepository = $this->createMock(TaskRepository::class);
        $taskRepository->expects(self::never())->method('hasActiveAutoGeneratedTaskForOpportunity');

        $entityManager = $this->createMock(EntityManagerInterface::class);
        $entityManager->expects(self::never())->method('persist');
        $entityManager->expects(self::never())->method('flush');

        $rule = new CreateTaskForHighScoreOpportunityRule($taskRepository, $entityManager, 80);

        $rule->execute(new OpportunityAnalyzed($opportunity, $this->makeAnalysisResult(), ['score', 'scoreReason']));
    }

    public function testExecuteCreatesTaskExactlyAtThresholdBoundary(): void
    {
        $opportunity = $this->makeOpportunity(80);

        $taskRepository = $this->createMock(TaskRepository::class);
        $taskRepository->method('hasActiveAutoGeneratedTaskForOpportunity')->willReturn(false);

        $entityManager = $this->createMock(EntityManagerInterface::class);
        $entityManager->expects(self::once())->method('persist');
        $entityManager->expects(self::once())->method('flush');

        $rule = new CreateTaskForHighScoreOpportunityRule($taskRepository, $entityManager, 80);

        $rule->execute(new OpportunityAnalyzed($opportunity, $this->makeAnalysisResult(), ['score', 'scoreReason']));
    }

    public function testExecuteDoesNothingWhenScoreIsNull(): void
    {
        $opportunity = $this->makeOpportunity(null);

        $taskRepository = $this->createMock(TaskRepository::class);
        $taskRepository->expects(self::never())->method('hasActiveAutoGeneratedTaskForOpportunity');

        $entityManager = $this->createMock(EntityManagerInterface::class);
        $entityManager->expects(self::never())->method('persist');
        $entityManager->expects(self::never())->method('flush');

        $rule = new CreateTaskForHighScoreOpportunityRule($taskRepository, $entityManager, 80);

        $rule->execute(new OpportunityAnalyzed($opportunity, $this->makeAnalysisResult(), ['score', 'scoreReason']));
    }

    public function testInjectedThresholdIsActuallyRespected(): void
    {
        // Preuve que le seuil injecté (et non une valeur en dur) est utilisé :
        // un score de 60 ne créerait pas de tâche avec le seuil par défaut
        // (80), mais en crée une avec un seuil abaissé à 50.
        $opportunity = $this->makeOpportunity(60);

        $taskRepository = $this->createMock(TaskRepository::class);
        $taskRepository->method('hasActiveAutoGeneratedTaskForOpportunity')->willReturn(false);

        $entityManager = $this->createMock(EntityManagerInterface::class);
        $entityManager->expects(self::once())->method('persist');
        $entityManager->expects(self::once())->method('flush');

        $rule = new CreateTaskForHighScoreOpportunityRule($taskRepository, $entityManager, 50);

        $rule->execute(new OpportunityAnalyzed($opportunity, $this->makeAnalysisResult(), ['score', 'scoreReason']));
    }

    // --- Idempotence -------------------------------------------------------

    public function testExecuteDoesNothingWhenAnActiveAutoGeneratedTaskAlreadyExists(): void
    {
        $opportunity = $this->makeOpportunity(90);

        $taskRepository = $this->createMock(TaskRepository::class);
        $taskRepository->method('hasActiveAutoGeneratedTaskForOpportunity')
            ->with($opportunity, CreateTaskForHighScoreOpportunityRule::AUTO_TASK_TITLE)
            ->willReturn(true);

        $entityManager = $this->createMock(EntityManagerInterface::class);
        $entityManager->expects(self::never())->method('persist');
        $entityManager->expects(self::never())->method('flush');

        $rule = new CreateTaskForHighScoreOpportunityRule($taskRepository, $entityManager, 80);

        $rule->execute(new OpportunityAnalyzed($opportunity, $this->makeAnalysisResult(), ['score', 'scoreReason']));
    }

    // --- Contenu de la Task créée --------------------------------------------

    public function testCreatedTaskHasExpectedTitlePriorityStatusOpportunityDueDateAndDescription(): void
    {
        $opportunity = $this->makeOpportunity(92, 'Excellente correspondance technique.');

        $taskRepository = $this->createMock(TaskRepository::class);
        $taskRepository->method('hasActiveAutoGeneratedTaskForOpportunity')->willReturn(false);

        /** @var Task|null $persistedTask */
        $persistedTask = null;
        $entityManager = $this->createMock(EntityManagerInterface::class);
        $entityManager->expects(self::once())
            ->method('persist')
            ->with(self::isInstanceOf(Task::class))
            ->willReturnCallback(function (object $entity) use (&$persistedTask): void {
                $persistedTask = $entity;
            });
        $entityManager->expects(self::once())->method('flush');

        $rule = new CreateTaskForHighScoreOpportunityRule($taskRepository, $entityManager, 80);

        $before = new \DateTimeImmutable();
        $rule->execute(new OpportunityAnalyzed($opportunity, $this->makeAnalysisResult(), ['score', 'scoreReason']));
        $after = new \DateTimeImmutable();

        self::assertInstanceOf(Task::class, $persistedTask);
        self::assertSame(CreateTaskForHighScoreOpportunityRule::AUTO_TASK_TITLE, $persistedTask->getTitle());
        self::assertSame(TaskPriority::HIGH, $persistedTask->getPriority());
        self::assertSame(TaskStatus::TODO, $persistedTask->getStatus());
        self::assertSame($opportunity, $persistedTask->getOpportunity());

        self::assertStringContainsString('92', (string) $persistedTask->getDescription());
        self::assertStringContainsString($opportunity->getTitle(), (string) $persistedTask->getDescription());
        self::assertStringContainsString('Excellente correspondance technique.', (string) $persistedTask->getDescription());

        // Échéance : "maintenant + 2 jours" (voir le commentaire de classe
        // ci-dessus sur les limites de ClockMock pour \DateTimeImmutable).
        self::assertNotNull($persistedTask->getDueDate());
        self::assertGreaterThanOrEqual($before->modify('+2 days')->getTimestamp(), $persistedTask->getDueDate()->getTimestamp());
        self::assertLessThanOrEqual($after->modify('+2 days')->getTimestamp(), $persistedTask->getDueDate()->getTimestamp());
    }

    public function testCreatedTaskDescriptionOmitsScoreReasonParagraphWhenScoreReasonIsEmpty(): void
    {
        $opportunity = $this->makeOpportunity(85, null);

        $taskRepository = $this->createMock(TaskRepository::class);
        $taskRepository->method('hasActiveAutoGeneratedTaskForOpportunity')->willReturn(false);

        /** @var Task|null $persistedTask */
        $persistedTask = null;
        $entityManager = $this->createMock(EntityManagerInterface::class);
        $entityManager->method('persist')->willReturnCallback(function (object $entity) use (&$persistedTask): void {
            $persistedTask = $entity;
        });

        $rule = new CreateTaskForHighScoreOpportunityRule($taskRepository, $entityManager, 80);

        $rule->execute(new OpportunityAnalyzed($opportunity, $this->makeAnalysisResult(), ['score', 'scoreReason']));

        self::assertInstanceOf(Task::class, $persistedTask);
        self::assertStringNotContainsString('Raison du score', (string) $persistedTask->getDescription());
    }
}
