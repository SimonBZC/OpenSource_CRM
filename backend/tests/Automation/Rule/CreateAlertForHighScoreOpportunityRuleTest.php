    // --- Contenu de l'Alerte créée --------------------------------------------

    public function testCreatedAlertHasExpectedTitlePriorityStatusOpportunityDueDateAndDescription(): void
    {
        $opportunity = $this->makeOpportunity(92, 'Excellente correspondance technique.');

        $alertRepository = $this->createMock(AlertRepository::class);
        $alertRepository->method('hasActiveAutoGeneratedAlertForOpportunity')->willReturn(false);

        /** @var Alert|null $persistedAlert */
        $persistedAlert = null;
        $entityManager = $this->createMock(EntityManagerInterface::class);
        $entityManager->expects(self::once())
            ->method('persist')
            ->with(self::isInstanceOf(Alert::class))
            ->willReturnCallback(function (object $entity) use (&$persistedAlert): void {
                $persistedAlert = $entity;
            });
        $entityManager->expects(self::once())->method('flush');

        $rule = new CreateAlertForHighScoreOpportunityRule($alertRepository, $entityManager, 80);

        $before = new \DateTimeImmutable();
        $rule->execute(new OpportunityAnalyzed($opportunity, $this->makeAnalysisResult(), ['score', 'scoreReason']));
        $after = new \DateTimeImmutable();

        self::assertInstanceOf(Alert::class, $persistedAlert);
        self::assertSame(CreateAlertForHighScoreOpportunityRule::AUTO_ALERT_TITLE, $persistedAlert->getTitle());
        self::assertSame(AlertPriority::HIGH, $persistedAlert->getPriority());
        self::assertSame(AlertStatus::TODO, $persistedAlert->getStatus());
        self::assertSame($opportunity, $persistedAlert->getOpportunity());

        self::assertStringContainsString('92', (string) $persistedAlert->getDescription());
        self::assertStringContainsString($opportunity->getTitle(), (string) $persistedAlert->getDescription());
        self::assertStringContainsString('Excellente correspondance technique.', (string) $persistedAlert->getDescription());

        // Échéance : "maintenant + 2 jours" (voir le commentaire de classe
        // ci-dessus sur les limites de ClockMock pour \DateTimeImmutable).
        self::assertNotNull($persistedAlert->getDueDate());
        self::assertGreaterThanOrEqual($before->modify('+2 days')->getTimestamp(), $persistedAlert->getDueDate()->getTimestamp());
        self::assertLessThanOrEqual($after->modify('+2 days')->getTimestamp(), $persistedAlert->getDueDate()->getTimestamp());
    }

    public function testCreatedAlertDescriptionOmitsScoreReasonParagraphWhenScoreReasonIsEmpty(): void
    {
        $opportunity = $this->makeOpportunity(85, null);

        $alertRepository = $this->createMock(AlertRepository::class);
        $alertRepository->method('hasActiveAutoGeneratedAlertForOpportunity')->willReturn(false);

        /** @var Alert|null $persistedAlert */
        $persistedAlert = null;
        $entityManager = $this->createMock(EntityManagerInterface::class);
        $entityManager->method('persist')->willReturnCallback(function (object $entity) use (&$persistedAlert): void {
            $persistedAlert = $entity;
        });

        $rule = new CreateAlertForHighScoreOpportunityRule($alertRepository, $entityManager, 80);

        $rule->execute(new OpportunityAnalyzed($opportunity, $this->makeAnalysisResult(), ['score', 'scoreReason']));

        self::assertInstanceOf(Alert::class, $persistedAlert);
        self::assertStringNotContainsString('Raison du score', (string) $persistedAlert->getDescription());
    }
}
