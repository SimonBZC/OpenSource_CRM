        $alertRepository->expects(self::never())->method('hasActiveAutoGeneratedAlertForOpportunity');

        $entityManager = $this->createMock(EntityManagerInterface::class);
        $entityManager->expects(self::never())->method('persist');
        $entityManager->expects(self::never())->method('flush');

        $rule = new CreateAlertForHighScoreOpportunityRule($alertRepository, $entityManager, 80);

        $rule->execute(new OpportunityAnalyzed($opportunity, $this->makeAnalysisResult(), ['score']));
    }

