/**
 * Test de bout en bout, entièrement en mémoire (pas de kernel, pas de DB, pas
 * de réseau), prouvant que la chaîne complète
 * POST /api/opportunities/{id}/analyze -> DomainEventBus ->
 * CreateTaskForHighScoreOpportunityRule -> persist(Task) fonctionne
 * réellement de bout en bout.
 *
 * Ce fichier comble un trou de couverture : ni
 * tests/Controller/OpportunityAnalysisControllerTest.php (qui câble un
 * DomainEventBus SANS règle), ni
 * tests/Automation/Rule/CreateTaskForHighScoreOpportunityRuleTest.php (qui
 * teste la règle isolément, sans passer par le contrôleur) ne prouvent que
 * l'automatisation se déclenche réellement à travers toute la chaîne
 * applicative.
 *
 * Même limitations de mock que OpportunityAnalysisControllerTest (voir sa
 * doc-comment) : App\Ai\OpportunityAnalyzer et App\Automation\DomainEventBus
 * sont `final`, donc non mockables directement — ils sont donc instanciés
 * réellement, alimentés par des dépendances mockées (LLMProviderInterface,
 * TaskRepository, EntityManagerInterface). SerializerInterface ne déclare pas
 * normalize() (qui vit sur NormalizerInterface), d'où le même double de test
 * fait main RecordingNormalizingSerializer (dupliqué localement, dans un
 * simple souci de ne pas coupler ce fichier à la visibilité d'une classe de
 * test définie dans un autre fichier).
 */
final class AnalyzeToTaskEndToEndTest extends TestCase
{
    private static ValidatorInterface $dtoValidator;

    public static function setUpBeforeClass(): void
    {
        self::$dtoValidator = Validation::createValidatorBuilder()
            ->enableAttributeMapping()
            ->getValidator();
    }

    private function makeOpportunity(): Opportunity
    {
        return (new Opportunity())->setTitle('Développeur Symfony senior');
    }

    /**
     * @return array<string, mixed>
     */
    private function validLlmPayload(array $overrides = []): array
    {
        return array_merge([
            'score' => 80,
            'relevant' => true,
            'technologies' => ['PHP', 'Symfony'],
            'tjm_min' => null,
            'tjm_max' => null,
            'remote' => true,
            'location' => null,
            'duration' => null,
            'start_date' => null,
            'reason' => 'Bonne correspondance avec le profil recherché.',
            'missing_information' => [],
        ], $overrides);
    }

    /**
     * Monte la chaîne complète (contrôleur réel -> analyzer réel -> applier
     * réel -> DomainEventBus réel -> vraie CreateTaskForHighScoreOpportunityRule),
     * avec pour seules dépendances mockées : le provider LLM, le repository
     * d'opportunités, le validator d'entité, le TaskRepository (idempotence)
     * et l'EntityManager (capture de persist()).
     *
     * @return array{0: OpportunityAnalysisController, 1: OpportunityRepository&\PHPUnit\Framework\MockObject\MockObject, 2: LLMProviderInterface&\PHPUnit\Framework\MockObject\MockObject, 3: EntityManagerInterface&\PHPUnit\Framework\MockObject\MockObject, 4: \ArrayObject<int, object>}
     */
    private function makeFullChain(bool $hasActiveAutoGeneratedTask = false): array
    {
        $repository = $this->createMock(OpportunityRepository::class);
        $llmProvider = $this->createMock(LLMProviderInterface::class);
        $analyzer = new OpportunityAnalyzer($llmProvider, self::$dtoValidator);

        // EntityManager unique, partagé entre le contrôleur (flush() de
        // l'Opportunity) et la règle d'automatisation (persist()+flush() de
        // la Task) : c'est exactement le montage de production, où les deux
        // reçoivent le même service Doctrine.
        $entityManager = $this->createMock(EntityManagerInterface::class);
        $persistedEntities = new \ArrayObject();
        $entityManager->method('persist')->willReturnCallback(
            static function (object $entity) use ($persistedEntities): void {
                $persistedEntities[] = $entity;
            },
        );

        $entityValidator = $this->createMock(ValidatorInterface::class);
        $entityValidator->method('validate')->willReturn(new ConstraintViolationList());

        $serializer = new EndToEndRecordingNormalizingSerializer();

        $applier = new OpportunityAnalysisApplier();

        $taskRepository = $this->createMock(TaskRepository::class);
        $taskRepository->method('hasActiveAutoGeneratedTaskForOpportunity')->willReturn($hasActiveAutoGeneratedTask);

        // La vraie règle d'automatisation, avec le seuil par défaut (80).
        $rule = new CreateTaskForHighScoreOpportunityRule($taskRepository, $entityManager);

        $dispatcher = new EventDispatcher();
        $eventBus = new DomainEventBus([$rule], $dispatcher, new NullLogger());

        $controller = new OpportunityAnalysisController(
            $repository,
            $analyzer,
            $entityManager,
            $entityValidator,
            $serializer,
            $applier,
            $eventBus,
        );

        return [$controller, $repository, $llmProvider, $entityManager, $persistedEntities];
    }

    /**
     * @return array<string, mixed>
     */
    private function decode(Response $response): array
    {
        self::assertInstanceOf(\Symfony\Component\HttpFoundation\JsonResponse::class, $response);
        $decoded = json_decode((string) $response->getContent(), true, 512, \JSON_THROW_ON_ERROR);
        self::assertIsArray($decoded);

        return $decoded;
    }

    /**
     * @param \ArrayObject<int, object> $persistedEntities
     */
    private function findPersistedTask(\ArrayObject $persistedEntities): ?Task
    {
        foreach ($persistedEntities as $entity) {
            if ($entity instanceof Task) {
                return $entity;
            }
        }

        return null;
    }

    // --- Cas nominal : score élevé -> Task créée ------------------------------

    public function testHighScoreAnalysisEndToEndCreatesAutoGeneratedTask(): void
    {
        $opportunity = $this->makeOpportunity();
        [$controller, $repository, $llmProvider, , $persistedEntities] = $this->makeFullChain();

        $repository->method('find')->willReturn($opportunity);
        $llmProvider->method('completeJson')->willReturn($this->validLlmPayload(['score' => 92]));

        $response = $controller->__invoke(1);

        // Non-régression Phase 7 : le contrat de réponse HTTP habituel.
        self::assertSame(Response::HTTP_OK, $response->getStatusCode());
        $body = $this->decode($response);
        self::assertSame(['opportunity', 'analysis', 'appliedFields'], array_keys($body));
        self::assertSame(92, $body['analysis']['score']);

        // Le score de l'Opportunity a bien été mis à jour.
        self::assertSame(92, $opportunity->getScore());

        // Preuve de bout en bout : une Task a effectivement été persist()ée
        // par la règle d'automatisation, déclenchée via le vrai DomainEventBus.
        $task = $this->findPersistedTask($persistedEntities);
        self::assertInstanceOf(Task::class, $task, 'Une Task auto-générée doit avoir été persist()ée pour un score élevé.');
        self::assertSame(CreateTaskForHighScoreOpportunityRule::AUTO_TASK_TITLE, $task->getTitle());
        self::assertSame(TaskPriority::HIGH, $task->getPriority());
        self::assertSame(TaskStatus::TODO, $task->getStatus());
        self::assertSame($opportunity, $task->getOpportunity());
    }

    // --- Cas négatif : score bas -> aucune Task créée -------------------------

    public function testLowScoreAnalysisEndToEndDoesNotCreateAnyTask(): void
    {
        $opportunity = $this->makeOpportunity();
        [$controller, $repository, $llmProvider, , $persistedEntities] = $this->makeFullChain();

        $repository->method('find')->willReturn($opportunity);
        $llmProvider->method('completeJson')->willReturn($this->validLlmPayload(['score' => 42]));

        $response = $controller->__invoke(1);

        self::assertSame(Response::HTTP_OK, $response->getStatusCode());
        $body = $this->decode($response);
        self::assertSame(42, $body['analysis']['score']);
        self::assertSame(42, $opportunity->getScore());

        // C'est bien la règle métier qui décide de ne pas créer de Task, et
        // non un effet de bord de la chaîne d'automatisation.
        self::assertNull($this->findPersistedTask($persistedEntities), 'Aucune Task ne doit être persist()ée pour un score sous le seuil.');
    }

    // --- Cas d'idempotence : score élevé mais Task active déjà existante -----

    public function testHighScoreAnalysisEndToEndDoesNotDuplicateTaskWhenOneAlreadyExists(): void
    {
        $opportunity = $this->makeOpportunity();
        [$controller, $repository, $llmProvider, , $persistedEntities] = $this->makeFullChain(hasActiveAutoGeneratedTask: true);

        $repository->method('find')->willReturn($opportunity);
        $llmProvider->method('completeJson')->willReturn($this->validLlmPayload(['score' => 92]));

        $response = $controller->__invoke(1);

        self::assertSame(Response::HTTP_OK, $response->getStatusCode());
        self::assertSame(92, $opportunity->getScore());

        // L'idempotence est prouvée à travers toute la chaîne : même avec un
        // score élevé, aucune Task supplémentaire n'est persist()ée si une
        // tâche auto-générée active existe déjà.
        self::assertNull($this->findPersistedTask($persistedEntities));
    }
}

/**
 * Double de test identique à
 * App\Tests\Controller\RecordingNormalizingSerializer, dupliqué localement
 * pour ce fichier (voir la doc-comment de classe ci-dessus).
 */
final class EndToEndRecordingNormalizingSerializer implements SerializerInterface, NormalizerInterface
{
    public mixed $lastObject = null;
    public ?string $lastFormat = null;
    /** @var array<string, mixed> */
    public array $lastContext = [];
    public mixed $returnValue = ['id' => 1];

    public function normalize(mixed $object, ?string $format = null, array $context = []): array|string|int|float|bool|\ArrayObject|null
    {
        $this->lastObject = $object;
        $this->lastFormat = $format;
        $this->lastContext = $context;

        return $this->returnValue;
    }

    public function supportsNormalization(mixed $data, ?string $format = null): bool
    {
        return true;
    }

    public function serialize(mixed $data, string $format, array $context = []): string
    {
        throw new \LogicException('EndToEndRecordingNormalizingSerializer::serialize() is not used by these tests.');
    }

    public function deserialize(mixed $data, string $type, string $format, array $context = []): mixed
    {
        throw new \LogicException('EndToEndRecordingNormalizingSerializer::deserialize() is not used by these tests.');
    }
}
